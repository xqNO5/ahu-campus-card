"""Extract DES tables/permutations from the school's des.js into a portable data module.

We deliberately parse the *original* served JavaScript rather than retyping tables,
so the port cannot drift from the server-side expectation.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = (ROOT / "des.js").read_text(encoding="utf-8", errors="replace")


def grab(name: str) -> str:
    """Return the raw JS declaration of `var name = [...];`."""
    m = re.search(r"var\s+" + re.escape(name) + r"\s*=\s*\[", SRC)
    if not m:
        raise SystemExit(f"table {name} not found")
    i = m.end() - 1
    depth = 0
    for j in range(i, len(SRC)):
        if SRC[j] == "[":
            depth += 1
        elif SRC[j] == "]":
            depth -= 1
            if depth == 0:
                return SRC[i : j + 1]
    raise SystemExit(f"unterminated table {name}")


def to_py(js: str) -> str:
    """JS array literal -> Python literal (uniformly a list of lists where nested)."""
    return js.replace("[", "[").replace("]", "]")


sboxes = {f"s{i}": grab(f"s{i}") for i in range(1, 9)}
loop = grab("loop")

# Everything below is a pure index map in the source, so read the maps statically
# rather than executing anything.

def read_index_map(fn_name: str, out_var: str, size: int):
    body = SRC[SRC.index(f"function {fn_name}") :]
    body = body[: body.index("return " + out_var)]
    m = {}
    for idx, val in re.findall(re.escape(out_var) + r"\[\s*(\d+)\]\s*=\s*\w+\[\s*(\d+)\s*\]", body):
        m[int(idx)] = int(val)
    assert len(m) == size, (fn_name, len(m))
    return [m[i] for i in range(size)]

p_box = read_index_map("pPermute", "pBoxPermute", 32)
fp_box = read_index_map("finallyPermute", "fpByte", 64)

# initPermute/expandPermute use loop arithmetic rather than literals; reimplement the
# arithmetic here (only the *indices* matter, so we track an identity array through it).
ip = [None] * 64
for i in range(4):
    m, n = 1 + 2 * i, 2 * i
    for k, j in enumerate(range(7, -1, -1)):
        ip[i * 8 + k] = j * 8 + m
        ip[i * 8 + k + 32] = j * 8 + n

ep = [None] * 48
for i in range(8):
    ep[i * 6 + 0] = 31 if i == 0 else i * 4 - 1
    ep[i * 6 + 1] = i * 4 + 0
    ep[i * 6 + 2] = i * 4 + 1
    ep[i * 6 + 3] = i * 4 + 2
    ep[i * 6 + 4] = i * 4 + 3
    ep[i * 6 + 5] = 0 if i == 7 else i * 4 + 4

assert sorted(ip) == list(range(64)), "initPermute is not a permutation"
assert len(set(ep)) == 32, "expandPermute should read 32 distinct bits"

out = ["# AUTO-GENERATED by tools/extract_des_tables.py -- do not edit by hand.",
       "# Source: the CAS login page's des.js served by wvpn.ahu.edu.cn",
       ""]
for name, js in sboxes.items():
    out.append(f"{name.upper()} = {to_py(js)}")
    out.append("")
out.append(f"KEY_SHIFT = {to_py(loop)}")
out.append("")
out.append(f"IP = {ip}")
out.append("")
out.append(f"EP = {ep}")
out.append("")
out.append(f"P_BOX = {p_box}")
out.append("")
out.append(f"FP = {fp_box}")
out.append("")

(ROOT / "ahu_client" / "des_tables.py").write_text("\n".join(out), encoding="utf-8")
print("wrote ahu_client/des_tables.py")
print("IP[:8]  =", ip[:8])
print("EP[:8]  =", ep[:8])
print("P_BOX   =", p_box[:8])
print("FP[:8]  =", fp_box[:8])

